"""Text twins of the LIVE Hunter category, one per payload file, written into ws/<first>-<last>/scenarios/.
Run with the repo venv from any cwd:
  build_live_twins.py --payloads DIR [--flow flow.json] [--passcode X] [--only SLUG ...] [--dry-run]
Every twin is `simulated` (Hunter persona verbatim, TARGET sentence as the goal), runs the flow's four
custom-code actions for real (`real_actions`) with the mock passcode in `action_envs`, and carries the Hunter
criteria verbatim in its description. `expect.intent` comes from EXITS (Hunter event -> DB intent); an event
not listed asserts nothing and is judged by rubric only. Files carry MARKER so build_workspaces.py-style
ownership rules hold: only marked files are rewritten or removed.
"""
import argparse
import glob
import json
import os
import re
import sys
import yaml
sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
WS_ROOT = os.path.join(HERE, "ws")
MARKER = "# generated by sim-fh/build_live_twins.py from the live Hunter pull; edit the payload, not this file"
REAL_ACTIONS = ["fhcsd_match_patient_fresh_auth", "fhcsd_get_patient_appointments_fresh_auth",
                "fhcsd_search_available_appointments_fresh_auth", "fhcsd_reschedule_appointment_fresh_auth"]
# Hunter event -> the DB intent the twin asserts (None = rubric only). Screening events end in a screening
# disposition, which the sim reports as the final intent (src/units/screening.py).
EXITS = {
    "happy_first_slot_copy": "Rescheduled", "happy_second_slot_copy": "Rescheduled", "two_values_one_breath_copy": "Rescheduled",
    "one_slot_returned_copy": "Rescheduled", "two_slots_returned_copy": "Rescheduled", "interrupts_readback_copy": "Rescheduled",
    "slot_corrected_after_choosing_copy": "Rescheduled", "dob_corrected_after_stating_copy": "Rescheduled",
    "dob_partial_then_complete_copy": "Rescheduled", "dob-misheard-then-correct": "Rescheduled",
    "none-of-these-then-date": "Rescheduled", "asks-unoffered-time": None, "slot-hesitation": None,
    "mildly-annoyed-not-upset": None, "closure-followup-question": "Rescheduled", "details-before-verification": None,
    "dob-fished": None, "asks-cost-midwalk": None, "asks-other-provider-location": None, "asks_second_appointment_copy": None,
    "preferred-weekend-date": None, "preferred-past-date": None, "retracts-after-choosing": None,
    "none-of-these-twice-declined": "Declined", "declines_upfront_copy": "Declined", "reschedule-callback-later": "Declined",
    "no_slots_copy": "No Availability", "no_appointment_on_file_copy": "Conflict Or API Failure",
    "token_401_copy": "Conflict Or API Failure", "save_html_409_copy": "Conflict Or API Failure",
    "booking_fails_copy": "Conflict Or API Failure", "already_has_appointment_copy": "Conflict Or API Failure",
    "dob_refused_copy": "Verification Failed", "dob_mismatch_copy": "Verification Failed",
    "lookup_no_match_copy": "Verification Failed", "lookup_two_matches_copy": "Verification Failed",
    "human_requested_copy": "Human Requested", "human-before-verification": "Human Requested",
    "emergency_copy": "Emergency Mentioned", "upset_copy": "Patient Upset",
    "hangs_up_midflow_copy": None,
    # screening entry (no --node): disposition names are the screening edge handles
    "wrong_person_spouse_copy": None, "voicemail_copy": None, "screening-callback-time": None,
    "screening-declined-do-not-call": None, "screening-wrong-number": None, "screening-emergency": None,
    "screening-human-requested": None,
}
SCREENING_EVENTS = {e for e in EXITS if e.startswith("screening-") or e in ("wrong_person_spouse_copy", "voicemail_copy")}
NOT_SIMULABLE = {"hangs_up_midflow_copy": "the simulated caller cannot go silent or hang up (engine aborts on an empty reply)"}


def slug_of(event: str) -> str:
    return "L-" + re.sub(r"[^a-z0-9]+", "-", event.replace("_copy", "").lower()).strip("-")


def persona_slug(p: dict) -> str:
    return re.sub(r"[^a-z0-9]+", "-", f"{p['first_name']} {p['last_name']}".lower()).strip("-")


def twin(payload_file: str, phone: str, passcode: str) -> tuple[dict, dict, str]:
    s = json.load(open(payload_file)); p = s["payload"]
    cp = p["conversationPrompt"]
    persona, sep, target = cp.rpartition("\n\nTARGET " if "\n\nTARGET " in cp else " TARGET ")
    assert sep and persona.strip() and target.strip(), f"{payload_file}: no TARGET sentence"
    criteria = re.findall(r"^\s*\d+\. .+$", p["evaluationPrompt"].split("Evaluate these criteria:")[1], re.M)
    assert criteria, f"{payload_file}: no numbered criteria"
    event = p["event"]; slug = slug_of(event); intent = EXITS.get(event)
    scenario = {
        "description": (f"Hunter {s['id']} {s['name']}. {s['description']}\n"
                        f"Exit -> {('DB intent ' + intent) if intent else 'no intent asserted (rubric only)'}.\n"
                        "Judged by the Hunter evaluationPrompt of this id, verbatim (judge.py); criteria:\n" + "\n".join(criteria)),
        "simulated_user": {"persona": persona.strip(), "goal": "TARGET " + target.strip(), "opening": "Hello?",
                           "max_turns": int(p.get("maxTurns") or 20)},
        "real_actions": REAL_ACTIONS,
        "action_envs": {"FHCSD_PASSCODE": passcode},
    }
    if intent:
        scenario["expect"] = {"intent": intent}
    else:
        # A twin that asserts no exit passes on any ending, including one that never reached the
        # flow's own outcome. The rubric still decides the score; this only stops a silent pass.
        scenario["expect"] = {"ended": True}
    params = {**p["initiationVariables"], "phone_number": phone}
    return scenario, params, slug


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--payloads", required=True); ap.add_argument("--passcode", default=os.environ.get("FHCSD_PASSCODE", ""))
    ap.add_argument("--only", nargs="*", default=[]); ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(a.payloads, "*.json")))
    files = [f for f in files if os.path.basename(f)[0].isdigit()]
    written, skipped = [], []
    for i, f in enumerate(files, 1):
        scenario, params, slug = twin(f, f"+1619555{i:04d}", a.passcode)
        if a.only and slug not in a.only:
            continue
        ws = os.path.join(WS_ROOT, persona_slug(params)); sdir = os.path.join(ws, "scenarios")
        event = json.load(open(f))["payload"]["event"]
        name = slug + (".yaml.disabled" if event in NOT_SIMULABLE else ".yaml")
        if event in NOT_SIMULABLE:
            scenario["disabled_reason"] = NOT_SIMULABLE[event]
        text = MARKER + "\n" + yaml.safe_dump(scenario, sort_keys=False, allow_unicode=True, width=110)
        if a.dry_run:
            print(f"{'DISABLED' if event in NOT_SIMULABLE else 'twin':8} {slug:40} -> {os.path.relpath(os.path.join(sdir, name), HERE)}  entry={'screening' if event in SCREENING_EVENTS else 'scheduler'}")
            continue
        os.makedirs(sdir, exist_ok=True)
        if not os.path.exists(os.path.join(ws, "flow.json")):
            os.symlink(os.path.join(HERE, "flow.json"), os.path.join(ws, "flow.json"))
        with open(os.path.join(ws, "params.yaml"), "w") as fh:
            fh.write("# generated by sim-fh/build_live_twins.py\n" + yaml.safe_dump({"params": params, "substitutions": {}}, sort_keys=False))
        with open(os.path.join(sdir, name), "w") as fh:
            fh.write(text)
        written.append(os.path.relpath(os.path.join(sdir, name), HERE))
    print(f"{'would write' if a.dry_run else 'wrote'} {len(files) if a.dry_run and not a.only else len(written)} twins; screening-entry events: {sorted(SCREENING_EVENTS)}")
    unknown = sorted({json.load(open(f))['payload']['event'] for f in files} - set(EXITS))
    if unknown:
        print("events with no EXITS entry (rubric only):", unknown)


if __name__ == "__main__":
    main()
