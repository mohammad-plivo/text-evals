"""Write one sim workspace per distinct persona from twins_table.TWINS and adversarial_table.ADVERSARIAL.

Run: .venv/bin/python build_workspaces.py [--self-test]   (any cwd; flow.json must exist, see build_flow.py)
Owns only scenario files whose first line is MARKER: rewrites them, removes stale ones, never touches others.
"""
import os
import re
import shutil
import sys
import tempfile

import yaml

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.environ.get("STRESS_REPO") or os.path.abspath(os.path.join(HERE, "..", "..", "repo"))  # STRESS_REPO pins a test tree
sys.path.insert(0, REPO)
sys.path.insert(0, HERE)

from src.simulation.cli.scenarios import Scenario  # noqa: E402
from src.simulation.cli.workspace import _PARAM_PLACEHOLDER, Workspace  # noqa: E402

FLOW = os.path.join(HERE, "flow.json")
WS_ROOT = os.path.join(HERE, "ws")
MARKER = "# generated by sim-fh/build_workspaces.py; edit the table module, not this file"
PERSONA_KEYS = ("first_name", "last_name", "date_of_birth", "phone_number")


def persona_slug(p):
    return re.sub(r"[^a-z0-9]+", "-", f"{p['first_name']} {p['last_name']}".lower()).strip("-")


def check_entry(e, table):
    where = f"{table} entry {e.get('slug')!r}"
    p = e.get("persona") or {}
    if not e.get("slug") or not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", e["slug"]):
        raise SystemExit(f"{where}: slug must be lowercase letters, digits, dashes and underscores")
    if sorted(p) != sorted(PERSONA_KEYS) or not all(str(p[k]).strip() for k in PERSONA_KEYS):
        raise SystemExit(f"{where}: persona needs exactly {PERSONA_KEYS}, all non-empty")
    if not re.fullmatch(r"\d{2}/\d{2}/\d{4}", p["date_of_birth"]):
        raise SystemExit(f"{where}: date_of_birth must be MM/DD/YYYY")
    body = {"simulated": "simulated_user", "scripted": "turns"}.get(e.get("kind"))
    if body is None or not e.get(body):
        raise SystemExit(f"{where}: kind must be simulated (with simulated_user) or scripted (with turns)")
    extra = set(e) - {"slug", "persona", "kind", body, "expect", "description", "disabled_reason"}
    if extra:
        raise SystemExit(f"{where}: unknown keys {sorted(extra)}")
    scenario = {"description": e.get("description", ""), body: e[body]}
    if e.get("expect"):
        scenario["expect"] = e["expect"]
    Scenario.model_validate({"name": e["slug"], **scenario})  # the CLI's own schema
    return scenario


def build(entries, ws_root=WS_ROOT, flow=FLOW):
    """entries: [(table_name, entry)]. Returns {persona_slug: [scenario file names]}."""
    personas, files, seen = {}, {}, set()
    for table, e in entries:
        scenario = check_entry(e, table)
        if e["slug"] in seen:
            raise SystemExit(f"duplicate slug {e['slug']!r}")
        seen.add(e["slug"])
        ps = persona_slug(e["persona"])
        if personas.setdefault(ps, e["persona"]) != e["persona"]:
            raise SystemExit(f"{e['slug']}: persona slug {ps!r} already used by a different persona {personas[ps]}")
        name = e["slug"] + (".yaml.disabled" if e.get("disabled_reason") else ".yaml")
        head = MARKER + f"\n# source: {table}\n"
        if e.get("disabled_reason"):
            head += f"# disabled: {e['disabled_reason']}\n"
        files.setdefault(ps, {})[name] = head + yaml.safe_dump(scenario, sort_keys=False, allow_unicode=True, width=100)

    for ps, persona in personas.items():
        ws = Workspace(root=os.path.join(ws_root, ps))
        os.makedirs(ws.scenarios_dir, exist_ok=True)
        os.makedirs(ws.reports_dir, exist_ok=True)
        shutil.copyfile(flow, ws.flow_path)
        with open(ws.params_path, "w") as f:
            f.write(MARKER + "\n" + yaml.safe_dump({"params": dict(persona), "substitutions": {}}, sort_keys=False))
        for name, text in files[ps].items():
            with open(os.path.join(ws.scenarios_dir, name), "w") as f:
                f.write(text)
        mapping = ws.load_mapping()
        placeholders = {m.group(0) for m in _PARAM_PLACEHOLDER.finditer(open(ws.flow_path).read())}
        missing = sorted(p for p in placeholders if not mapping.get(p))
        if missing:
            raise SystemExit(f"{ws.root}: placeholders without a value: {missing}")
        if any(n.endswith(".yaml") for n in files[ps]):
            ws.load_scenarios()  # the CLI's own loader parses every enabled file

    removed = []
    for ps in sorted(os.listdir(ws_root)) if os.path.isdir(ws_root) else []:
        sdir = os.path.join(ws_root, ps, "scenarios")
        for name in sorted(os.listdir(sdir)) if os.path.isdir(sdir) else []:
            path = os.path.join(sdir, name)
            if name in files.get(ps, {}) or not os.path.isfile(path):
                continue
            with open(path) as f:
                owned = f.readline().rstrip("\n") == MARKER
            if owned:
                os.remove(path)
                removed.append(os.path.relpath(path, ws_root))
    return {ps: sorted(files[ps]) for ps in personas}, removed


def self_test():
    persona = {"first_name": "Test", "last_name": "Person", "date_of_birth": "01/02/1990", "phone_number": "+16195550100"}
    sim = {"slug": "a-sim", "persona": persona, "kind": "simulated", "expect": {"ended": True},
           "simulated_user": {"persona": "Calm.", "goal": "Say goodbye."}, "description": "d"}
    off = {"slug": "b-off", "persona": persona, "kind": "scripted", "turns": [{"user": "Hello?"}],
           "disabled_reason": "parked"}
    with tempfile.TemporaryDirectory() as tmp:
        sdir = os.path.join(tmp, "test-person", "scenarios")
        out, removed = build([("TWINS", sim), ("ADVERSARIAL", off)], ws_root=tmp)
        assert out == {"test-person": ["a-sim.yaml", "b-off.yaml.disabled"]} and not removed, out
        with open(os.path.join(sdir, "hand-written.yaml"), "w") as f:
            f.write("description: not owned\nturns:\n  - user: hi\n")
        first = open(os.path.join(sdir, "a-sim.yaml")).read()
        build([("TWINS", sim), ("ADVERSARIAL", off)], ws_root=tmp)
        assert open(os.path.join(sdir, "a-sim.yaml")).read() == first, "second run changed a file"
        out, removed = build([("TWINS", sim)], ws_root=tmp)
        assert removed == ["test-person/scenarios/b-off.yaml.disabled"], removed
        assert sorted(os.listdir(sdir)) == ["a-sim.yaml", "hand-written.yaml"], os.listdir(sdir)
        assert os.path.isdir(os.path.join(tmp, "test-person", "reports"))
        params = yaml.safe_load(open(os.path.join(tmp, "test-person", "params.yaml")))["params"]
        assert params == persona, params
        for bad in ({**sim, "persona": {**persona, "date_of_birth": "1990-01-02"}}, {**sim, "kind": "scripted"}):
            try:
                build([("TWINS", bad)], ws_root=tmp)
                raise AssertionError("bad entry accepted")
            except SystemExit:
                pass
    print("self-test OK: write, idempotent rerun, stale owned file removed, hand-written file kept, bad entries refused")


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        self_test()
        sys.exit(0)
    from adversarial_table import ADVERSARIAL
    from twins_table import TWINS

    out, removed = build([("TWINS", e) for e in TWINS] + [("ADVERSARIAL", e) for e in ADVERSARIAL])
    n = sum(map(len, out.values()))
    print(f"{len(out)} persona workspaces, {n} scenario files under {WS_ROOT}; removed stale: {removed or 'none'}")
    for ps, names in out.items():
        print(f"  {ps}: {len(names)} files, every {{{{Start...params...}}}} placeholder resolved")
