def show(rule: dict) -> str:
    (op, v), = rule.items()
    return {"contains_all": lambda: "contains " + " + ".join(v), "digits": lambda: f"digits {v}",
            "date": lambda: f"date {v}", "ci": lambda: f"{v} (any case)"}.get(op, lambda: str(v))()


def code_checks(s: dict, base: dict) -> list[str]:
    out = [f"exit `{s['expect_exit']}`"]
    diff = [f"`{f}` {show(r)}" for f, r in s["expect_saved"].items() if base.get(f) != r]
    if s["expect_saved"]:
        out.append("saves every required field" + (f"; changed from the fact sheet: {', '.join(diff)}" if diff else ""))
    out += [f"`{f}` never saved as {', '.join(v)} (carried, not graded yet)" for f, v in s["never_saved"].items()]
    if s["expect_unsaved"]:
        out.append(f"leaves {', '.join(f'`{f}`' for f in s['expect_unsaved'])} unsaved")
    tools = []
    for t in s["expect_tools"]:
        if t["tool"] == "log_call_note":
            tools.append(f"`log_call_note` (row has {', '.join(t['args']['values']['contains_all'])})")
        elif t["tool"] == "book_visit":
            tools.append("`book_visit` once with the saved values and account NW-20417")
        else:
            tools.append(f"`{t['tool']}` ({', '.join(f'{k} {show(r)}' for k, r in t['args'].items())})")
    out.append("tools: " + ", ".join(tools) + (f"; never {', '.join(f'`{t}`' for t in s['forbid_tools'])}" if s["forbid_tools"] else ""))
    extra = s["agent_never_says"][4:]  # the first four are the PIN's spoken forms, on every walk
    if extra:
        out.append(f"agent never says {' or '.join(f'`{x}`' for x in extra)} (carried, not graded yet)")
    return out


