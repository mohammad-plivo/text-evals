def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("convert")
    c.add_argument("--only", nargs="*", default=[])
    c.add_argument("--day", help="run day, YYYY-MM-DD; default today in America/New_York")
    a = ap.parse_args()
    spec = json.load(open(SPEC))
    day = date.fromisoformat(a.day) if a.day else datetime.now(ZoneInfo(spec["dates"]["timezone"])).date()
    subs = dates(day)
    scns = [fill(s, subs) for s in spec["scenarios"]]
    for s in scns:
        validate(s, spec["flow"])
        if not a.only or s["slug"] in a.only:
            write_pack(s, day, subs)
            print(f"{s['slug']:26} exit={s['expect_exit']:19} mocks={s['mock_variant']:15} "
                  f"tools={len(s['expect_tools'])} saved={len(s['expect_saved'])}")
    open(os.path.join(HERE, "SCENARIOS.md"), "w").write(scenarios_md(scns, day, subs))


if __name__ == "__main__":
    main()
