"""Example-flow lane: spec.json -> pack/<slug>/, the layout lane.py convert writes for the FHCSD twins.

  python3 ex_lane.py convert [--only SLUG ...] [--day YYYY-MM-DD]

Each pack/<slug>/ gets scenario.yaml (caller and mocks, read by the sim CLI), params.yaml (the Start payload run_one.py
seeds) and spec.json (what judge_lane.py grades). Dates come from the run day in America/New_York, so convert again on
the day of a run. Also rewrites SCENARIOS.md. $0: no network, no ledger.
"""
