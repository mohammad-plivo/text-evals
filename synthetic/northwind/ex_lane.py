SPEC, PACK = os.path.join(HERE, "spec.json"), os.path.join(HERE, "pack")
TOKEN = re.compile(r"\{(?:VISIT2?|PAST)_(?:SPOKEN|ISO)\}")
KEYS = re.compile(make_spec.KEYS_RE)
SHARED = {"GO-AHEAD BEFORE BOOKING", "BOOKING CONFIRMED", "PIN NEVER SPOKEN", "NOTHING INVENTED", "CLEAN CLOSE"}


def dates(day: date) -> dict[str, str]:
    visit = day + timedelta(days=14)
    visit += timedelta(days=(1 - visit.weekday()) % 7)  # first Tuesday at least 14 days out
    visit2, past = visit + timedelta(days=2), day - timedelta(days=day.weekday() or 7)  # past: last Monday strictly before

    def spoken(d: date) -> str:
        return f"{d:%A} the {lane.ordinal(d.day)} of {d:%B}"
    return {"{VISIT_SPOKEN}": spoken(visit), "{VISIT_ISO}": visit.isoformat(), "{VISIT2_SPOKEN}": spoken(visit2),
            "{VISIT2_ISO}": visit2.isoformat(), "{PAST_SPOKEN}": f"{past:%A}, {past:%B} {lane.ordinal(past.day)}, {past.year}",
            "{PAST_ISO}": past.isoformat()}


def fill(obj, subs: dict[str, str]):
    text = json.dumps(obj, ensure_ascii=False)
    for k, v in subs.items():
        text = text.replace(k, v)
    left = sorted(set(TOKEN.findall(text)))
    assert not left, f"unfilled {left} in {text[:80]}"
    return json.loads(text)


def validate(s: dict, flow: dict) -> None:
    agent = next(n for n in flow["nodes"] if n["type"] == "ai_agent_v29")["data"]["config"]
    intents = {i["intent_name"] for i in agent["intents"]}
    actions = {a["http_tool_name"] for a in agent["actions"]}
    assert s["expect_exit"] in intents, f"{s['slug']}: exit {s['expect_exit']} is not a flow intent"
    assert actions <= set(s["action_mocks"]), f"{s['slug']}: unmocked {actions - set(s['action_mocks'])}"
    assert {t["tool"] for t in s["expect_tools"]} | set(s["forbid_tools"]) <= actions, s["slug"]
    if "account_pin" in s["expect_saved"]:  # the keypad line the caller sends is the PIN the walk must save
        typed = [re.sub(r"\s", "", k) for k in KEYS.findall(s["goal"])]
        assert typed and set(typed) == {s["expect_saved"]["account_pin"]["eq"]}, f"{s['slug']}: keys {typed}"


def judge_spec(s: dict, day: date, subs: dict) -> dict:
    rule = f"runs {', '.join(t['tool'] for t in s['expect_tools'])}" + (
        f"; never {', '.join(s['forbid_tools'])}" if s["forbid_tools"] else "")
    return {"slug": s["slug"], "source": f"{SPEC}#{s['slug']}", "rubric": s["rubric"], "threshold": 0.8,
            "judge_model": "gpt-4.1", "expect_exit": s["expect_exit"], "expect_tools": s["expect_tools"],
            "forbid_tools": s["forbid_tools"], "tools_rule": [rule], "search_tool": None, "idle_limit_s": 15,
            "entry": "flow", "caller_dates": [], "run_day": day.isoformat(), "dates": subs, "params": s["params"],
            **{k: s[k] for k in ("expect_saved", "expect_unsaved", "never_saved", "agent_never_says", "group", "type",
                                 "facet", "title", "move", "defects", "mock_variant", "est_caller_turns")}}


def write_pack(s: dict, day: date, subs: dict) -> None:
    out = os.path.join(PACK, s["slug"])
    os.makedirs(out, exist_ok=True)
    scenario = {"description": f"Northwind example flow, {s['type'] or s['group']} / {s['facet']}: {s['title']}. "
                               f"Catches {', '.join(s['defects'])}. Dates for {day}.",
                "simulated_user": {k: s[k] for k in ("persona", "goal", "opening", "max_turns")},
                "action_mocks": s["action_mocks"], "expect": {"intent": s["expect_exit"]}}
    with open(os.path.join(out, "scenario.yaml"), "w") as fh:
        fh.write("# generated by example-flow/ex_lane.py convert from spec.json; synthetic data, mocks only\n")
        yaml.safe_dump(scenario, fh, sort_keys=False, allow_unicode=True, width=110)
    with open(os.path.join(out, "params.yaml"), "w") as fh:
        yaml.safe_dump({"params": s["params"], "substitutions": {}}, fh, sort_keys=False)
    json.dump(judge_spec(s, day, subs), open(os.path.join(out, "spec.json"), "w"), indent=1, ensure_ascii=False)


